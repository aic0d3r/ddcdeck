#!/usr/bin/env python3
"""Collect every i18n.T("...") string in the Go sources into internal/i18n/locales/template.toml.
Translators copy it to <lang>.toml (e.g. de.toml, pt_BR.toml) and fill in the right-hand
sides; untranslated lines can stay as they are or be deleted. Run via `make i18n`; CI fails
if the committed template is stale."""
import json
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
pat = re.compile(r'i18n\.T\(("(?:[^"\\]|\\.)*")\)')
strings = set()
for p in (root / "internal").rglob("*.go"):
    if p.name.endswith("_test.go") or "i18n" in p.parts:
        continue
    for m in pat.finditer(p.read_text()):
        strings.add(json.loads(m.group(1)))  # Go and JSON agree on the escapes used here

out = [
    "# Translation template: copy to <lang>.toml and translate the right-hand sides.",
    "# Generated by scripts/gen-locale-template.py - do not edit.",
    "",
]
out += [f"{json.dumps(s, ensure_ascii=False)} = {json.dumps(s, ensure_ascii=False)}" for s in sorted(strings)]
(root / "internal" / "i18n" / "locales" / "template.toml").write_text("\n".join(out) + "\n")
